CREATE TABLE bk_foods AS SELECT * FROM foods;
CREATE TABLE bk_plan AS SELECT * FROM plan;
CREATE TABLE bk_shopping AS SELECT * FROM shopping;
CREATE TABLE bk_images AS SELECT * FROM food_images;
DROP TABLE food_images;
DROP TABLE shopping;
DROP TABLE plan;
DROP TABLE foods;
CREATE TABLE IF NOT EXISTS foods (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, kind TEXT NOT NULL, category TEXT, unit TEXT, price INTEGER, place TEXT, note TEXT, created_at TEXT NOT NULL DEFAULT (datetime('now')));
CREATE UNIQUE INDEX IF NOT EXISTS idx_foods_name ON foods(name COLLATE NOCASE, kind);
CREATE TABLE IF NOT EXISTS plan (id INTEGER PRIMARY KEY AUTOINCREMENT, date TEXT NOT NULL, meal TEXT NOT NULL CHECK (meal IN ('sang','phu_sang','trua','phu','toi','phu_toi')), food_id INTEGER NOT NULL REFERENCES foods(id) ON DELETE CASCADE, servings REAL NOT NULL DEFAULT 1, note TEXT, created_at TEXT NOT NULL DEFAULT (datetime('now')));
CREATE INDEX IF NOT EXISTS idx_plan_date ON plan(date);
CREATE TABLE IF NOT EXISTS shopping (id INTEGER PRIMARY KEY AUTOINCREMENT, food_id INTEGER REFERENCES foods(id) ON DELETE SET NULL, name TEXT NOT NULL, qty REAL, unit TEXT, category TEXT, note TEXT, est INTEGER, price INTEGER, source TEXT NOT NULL DEFAULT 'manual' CHECK (source IN ('plan','manual')), bought_at TEXT, cleared INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL DEFAULT (datetime('now')));
CREATE INDEX IF NOT EXISTS idx_shopping_open ON shopping(cleared);
CREATE INDEX IF NOT EXISTS idx_shopping_bought ON shopping(bought_at);
CREATE TABLE IF NOT EXISTS food_images (food_id INTEGER PRIMARY KEY REFERENCES foods(id) ON DELETE CASCADE, mime TEXT NOT NULL, data TEXT NOT NULL, updated_at TEXT NOT NULL DEFAULT (datetime('now')));
INSERT INTO foods (id, name, kind, category, unit, price, place, note, created_at) SELECT id, name, kind, category, unit, price, place, note, created_at FROM bk_foods;
INSERT INTO plan (id, date, meal, food_id, servings, created_at) SELECT id, date, meal, food_id, servings, created_at FROM bk_plan;
INSERT INTO shopping (id, food_id, name, qty, unit, category, note, est, price, source, bought_at, cleared, created_at) SELECT id, food_id, name, qty, unit, category, note, est, price, source, bought_at, cleared, created_at FROM bk_shopping;
INSERT INTO food_images (food_id, mime, data, updated_at) SELECT food_id, mime, data, updated_at FROM bk_images;
DROP TABLE bk_images;
DROP TABLE bk_shopping;
DROP TABLE bk_plan;
DROP TABLE bk_foods;
